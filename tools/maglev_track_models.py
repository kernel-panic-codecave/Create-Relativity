#!/usr/bin/env python3
"""Maglev track's models: a guideway trough |\\_______/| swept along each track shape's path (block models), and the
pieces Create sweeps along curves (tie: a floor underlay; segment_left/right: one wall and half the floor each, stretched
along each rail). Writes OBJ models, their JSONs, the blockstate and the texture under src/main/resources.

Profile in pixels (16 per block), across the track from its centre line and up from the block's bottom."""
import json, math, os, random
from PIL import Image

ROOT = os.path.join(os.path.dirname(__file__), '..', 'src', 'main', 'resources', 'assets', 'create_relativity')
MODELS = os.path.join(ROOT, 'models', 'block', 'maglev_track')
NS = 'create_relativity'

FLOOR = 15        # floor half-width
TOP = 1           # floor top
BOTTOM = -2       # underside
WALL_IN = 21      # wall top's inner edge (the slope runs from the floor's edge up to it)
WALL_OUT = 23     # outer face
WALL_TOP = 7

# Convex parts, counter-clockwise (x across, y up); edges marked False are internal (between parts) and not drawn.
FLOOR_PART = [((-FLOOR, BOTTOM), 'bottom'), ((FLOOR, BOTTOM), None), ((FLOOR, TOP), 'floor'), ((-FLOOR, TOP), None)]
RIGHT_WALL = [((FLOOR, BOTTOM), 'bottom'), ((WALL_OUT, BOTTOM), 'outer'), ((WALL_OUT, WALL_TOP), 'top'),
              ((WALL_IN, WALL_TOP), 'slope'), ((FLOOR, TOP), None)]
LEFT_WALL = [((-WALL_OUT, BOTTOM), 'bottom'), ((-FLOOR, BOTTOM), None), ((-FLOOR, TOP), 'slope'),
             ((-WALL_IN, WALL_TOP), 'top'), ((-WALL_OUT, WALL_TOP), 'outer')]

# Texture: 32 wide (along the track, 16 px a block), 64 tall in bands (across the profile).
TEX_W, TEX_H = 32, 64
BANDS = {'floor': (0, 30), 'slope': (30, 39), 'top': (39, 41), 'outer': (41, 50), 'bottom': (50, 58), 'cap': (58, 64)}


def band_v(kind, a, b, p):
    """Texture v (pixels) of profile point p on edge a->b of the given kind."""
    lo, hi = BANDS[kind]
    if kind == 'floor':
        # Across the whole floor (so the halves of a curve piece line up): left edge at lo.
        return lo + (p[0] + FLOOR) / (2 * FLOOR) * (hi - lo)
    if kind == 'slope' or kind == 'top' or kind == 'outer':
        # From the floor side up/out: by distance from the edge's lower/inner end.
        ends = sorted([a, b], key=lambda q: (abs(q[0]) if kind == 'top' else q[1]))
        length = math.dist(*ends)
        t = math.dist(ends[0], p) / length if length else 0.0
        return lo + t * (hi - lo)
    return lo + (p[0] + WALL_OUT) / (2 * WALL_OUT) * (hi - lo)


class Mesh:
    def __init__(self):
        self.v, self.vt, self.vn, self.f = [], [], [], []

    def quad(self, pts, uvs, normal):
        # Wind so the geometric normal agrees with the intended one.
        e1 = [pts[1][i] - pts[0][i] for i in range(3)]
        e2 = [pts[2][i] - pts[0][i] for i in range(3)]
        g = (e1[1] * e2[2] - e1[2] * e2[1], e1[2] * e2[0] - e1[0] * e2[2], e1[0] * e2[1] - e1[1] * e2[0])
        if sum(g[i] * normal[i] for i in range(3)) < 0:
            pts, uvs = pts[::-1], uvs[::-1]
        n = math.sqrt(sum(c * c for c in normal)) or 1.0
        self.vn.append(tuple(c / n for c in normal))
        idx = []
        for p, uv in zip(pts, uvs):
            self.v.append(p)
            self.vt.append((uv[0] / TEX_W, 1.0 - uv[1] / TEX_H))  # (flip_v)
            idx.append((len(self.v), len(self.vt), len(self.vn)))
        if len(idx) == 3:
            idx.append(idx[2])
        self.f.append(idx)

    def write(self, path):
        with open(path, 'w') as out:
            out.write('# Generated by tools/maglev_track_models.py\nmtllib maglev_track.mtl\nusemtl maglev\n')
            for p in self.v: out.write('v %.6f %.6f %.6f\n' % p)
            for t in self.vt: out.write('vt %.6f %.6f\n' % t)
            for n in self.vn: out.write('vn %.6f %.6f %.6f\n' % n)
            for face in self.f: out.write('f ' + ' '.join('%d/%d/%d' % i for i in face) + '\n')


def sweep(mesh, p0, p1, parts, caps=True, lift=0.0, u0=0.0, place=None):
    """The profile's parts swept straight from p0 to p1 (blocks), kept upright (sheared up slopes)."""
    d = [p1[i] - p0[i] for i in range(3)]
    h = math.hypot(d[0], d[2])
    t = (d[0] / h, 0.0, d[2] / h)
    r = (t[2], 0.0, -t[0])  # across, horizontal
    length = math.sqrt(sum(c * c for c in d))
    u1 = u0 + length * 16

    def at(base, q):
        x, y = q[0] / 16.0, q[1] / 16.0 + lift
        if place: return place(base, x, y)
        return (base[0] + r[0] * x, base[1] + y, base[2] + r[2] * x)

    for part in parts:
        pts = [q for q, _ in part]
        for k, (a, kind) in enumerate(part):
            if kind is None: continue
            b = pts[(k + 1) % len(pts)]
            n2 = (b[1] - a[1], -(b[0] - a[0]))  # outward (counter-clockwise polygon)
            normal = (r[0] * n2[0], n2[1], r[2] * n2[0])
            quad = [at(p0, a), at(p0, b), at(p1, b), at(p1, a)]
            va, vb = band_v(kind, a, b, a), band_v(kind, a, b, b)
            mesh.quad(quad, [(u0, va), (u0, vb), (u1, vb), (u1, va)], normal)
        if caps:
            lo, hi = BANDS['cap']
            cuv = [((q[0] + WALL_OUT) / (2 * WALL_OUT) * TEX_W, hi - (q[1] - BOTTOM) / (WALL_TOP - BOTTOM) * (hi - lo)) for q in pts]
            for base, sign in ((p0, -1.0), (p1, 1.0)):
                normal = (t[0] * sign, d[1] / h * 0 * sign, t[2] * sign)
                for k in range(1, len(pts) - 1):
                    mesh.quad([at(base, pts[0]), at(base, pts[k]), at(base, pts[k + 1])], [cuv[0], cuv[k], cuv[k + 1]], normal)


WALLED = [FLOOR_PART, RIGHT_WALL, LEFT_WALL]
FLOOR_ONLY = [FLOOR_PART]

PATHS = {
    'zo': ((0.5, 0, 0), (0.5, 0, 1)),
    'xo': ((0, 0, 0.5), (1, 0, 0.5)),
    'pd': ((0, 0, 0), (1, 0, 1)),
    'nd': ((1, 0, 0), (0, 0, 1)),
    'as': ((0.5, 0, 0), (0.5, 1, 1)),
    'an': ((0.5, 1, 0), (0.5, 0, 1)),
    'ae': ((0, 0, 0.5), (1, 1, 0.5)),
    'aw': ((0, 1, 0.5), (1, 0, 0.5)),
}
CROSSINGS = {'cr_o': ('zo', 'xo'), 'cr_d': ('pd', 'nd'), 'cr_pdx': ('pd', 'xo'), 'cr_pdz': ('pd', 'zo'),
             'cr_ndx': ('nd', 'xo'), 'cr_ndz': ('nd', 'zo')}

# Create sweeps curves with these: the tie at each segment's centre, the rail pieces between the rails' points at
# ±0.965 across, stretched along z (0..0.5); a model's y is 0.068 below the block model's (as Create's are).
RAIL = 0.965
CURVE_DROP = 0.068


def curve_piece(side):
    """One wall and half the floor (side +1: the +x half), in rail-local coordinates."""
    m = Mesh()
    half = [((0, BOTTOM), 'bottom'), ((FLOOR, BOTTOM), None), ((FLOOR, TOP), 'floor'), ((0, TOP), None)]
    wall = RIGHT_WALL
    parts = [half, wall]
    if side < 0:
        parts = [[((-q[0], q[1]), k) for q, k in reversed(rotate_kinds(p))] for p in parts]

    def place(base, x, y):
        return (x - side * RAIL, y - CURVE_DROP, base[2])
    sweep(m, (0, 0, 0), (0, 0, 0.5), parts, caps=False, place=place, u0=0.0)
    return m


def rotate_kinds(part):
    """A part with each edge's kind moved to the edge's other end (for mirroring: reversing the polygon flips it)."""
    pts = [q for q, _ in part]
    kinds = [k for _, k in part]
    # Edge k runs pts[k] -> pts[k+1]; reversed, it runs pts[k+1] -> pts[k]: label it at pts[k+1].
    return [(pts[(k + 1) % len(pts)], kinds[k]) for k in range(len(pts))]


def tie():
    m = Mesh()
    under = [((-FLOOR, BOTTOM), 'bottom'), ((FLOOR, BOTTOM), 'bottom'), ((FLOOR, TOP - 0.06), 'floor'), ((-FLOOR, TOP - 0.06), 'bottom')]

    def place(base, x, y):
        return (0.5 + x, y - CURVE_DROP, base[2])
    sweep(m, (0, 0, -0.125), (0, 0, 0.625), [under], caps=False, place=place)
    return m


def texture(north=(176, 58, 58), south=(58, 93, 176)):
    """The guideway's texture; [north]/[south] the magnets' pole colours. (No line down the floor's middle: at a junction
    every path's would cross the others'.)"""
    random.seed(7)
    img = Image.new('RGBA', (TEX_W, TEX_H))
    px = img.load()

    def noisy(base, amount):
        return tuple(max(0, min(255, int(c + random.uniform(-amount, amount)))) for c in base) + (255,)
    for y in range(TEX_H):
        for x in range(TEX_W):
            if y < 30:  # floor: light concrete, darker toward the walls
                edge = min(y, 29 - y)
                base = (178, 184, 192) if edge > 2 else (150, 156, 166)
                if x % 16 == 0: base = tuple(c - 14 for c in base)  # expansion joint each block
                px[x, y] = noisy(base, 5)
            elif y < 39:  # slope: a row of magnets (after Simulated's redstone magnet), poles alternating, coils wound round
                phase = x % 8
                pole = north if (x // 8) % 2 == 0 else south
                frame = (60, 63, 70)
                if y in (30, 38):
                    base = frame
                elif y in (31, 37):  # copper windings
                    base = (224, 149, 106) if x % 2 == 0 else (154, 90, 62)
                elif phase in (0, 7) or y in (32, 36):
                    base = frame
                elif phase in (3, 4) and y in (34, 35):
                    base = (111, 115, 120)  # the pole's iron face
                else:
                    shade = {33: 1.12, 34: 1.0, 35: 0.94, 36: 0.86}.get(y, 1.0)
                    base = tuple(min(255, int(c * shade)) for c in pole)
                px[x, y] = noisy(base, 3)
            elif y < 41:  # wall top: edge-worn concrete
                px[x, y] = noisy((200, 204, 210), 6)
            elif y < 50:  # outer face
                base = (168, 174, 182) if y > 41 else (190, 194, 200)
                if x % 16 == 0: base = (140, 146, 156)
                px[x, y] = noisy(base, 6)
            elif y < 58:
                px[x, y] = noisy((120, 124, 130), 5)
            else:  # caps
                px[x, y] = noisy((160, 166, 174), 6)
    return img


def item_texture(north=(176, 58, 58, 255), south=(58, 93, 176, 255)):
    img = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
    px = img.load()
    # The profile, end on, shaded: walls, slopes with their magnets, the floor; and the floor running back.
    concrete, dark, steel = (184, 190, 198, 255), (130, 136, 146, 255), (96, 106, 122, 255)
    for x in range(16):
        for y in range(9, 13): px[x, y] = concrete if y > 9 else (205, 209, 215, 255)
    for y in range(12, 15):
        for x in range(16): px[x, y] = dark
    for x in (0, 1, 14, 15):
        for y in range(4, 15): px[x, y] = concrete
    for k in range(5):
        px[2 + k, 5 + k] = steel
        px[13 - k, 5 + k] = steel
        px[2 + k, 4 + k] = (north if k == 1 else south) if k in (1, 2) else concrete
        px[13 - k, 4 + k] = (south if k == 1 else north) if k in (1, 2) else concrete
    for x in range(16): px[x, 15] = (90, 96, 104, 255)
    return img


def model_json(obj):
    return {"parent": f"{NS}:block/maglev_track/obj_track", "loader": "neoforge:obj", "flip_v": True,
            "model": f"{NS}:models/block/maglev_track/{obj}.obj"}


def main():
    os.makedirs(MODELS, exist_ok=True)
    for f in os.listdir(MODELS):
        if f.endswith('.json') or f.endswith('.obj') or f.endswith('.mtl'): os.remove(os.path.join(MODELS, f))
    with open(os.path.join(MODELS, 'maglev_track.mtl'), 'w') as out:
        out.write('newmtl maglev\nmap_Kd #0\n')
    json.dump({"parent": "block/block", "ambientocclusion": False, "render_type": "minecraft:cutout_mipped",
               "textures": {"0": f"{NS}:block/maglev_track", "particle": f"{NS}:block/maglev_track"}},
              open(os.path.join(MODELS, 'obj_track.json'), 'w'), indent=2)

    def emit(name, mesh):
        mesh.write(os.path.join(MODELS, name + '.obj'))
        json.dump(model_json(name), open(os.path.join(MODELS, name + '.json'), 'w'), indent=2)

    for name, (a, b) in PATHS.items():
        m = Mesh()
        sweep(m, a, b, WALLED)
        emit(name, m)
    for name, (one, two) in CROSSINGS.items():
        m = Mesh()
        sweep(m, *PATHS[one], FLOOR_ONLY)
        sweep(m, *PATHS[two], FLOOR_ONLY, lift=0.002)
        emit(name, m)
    emit('tie', tie())
    emit('segment_left', curve_piece(1))
    emit('segment_right', curve_piece(-1))

    variants = {}
    shapes = list(PATHS) + list(CROSSINGS)
    for s in shapes: variants[f"shape={s}"] = {"model": f"{NS}:block/maglev_track/{s}"}
    variants["shape=none"] = {"model": "minecraft:block/air"}
    for s, along in (('tn', 'zo'), ('ts', 'zo'), ('te', 'xo'), ('tw', 'xo')):
        variants[f"shape={s}"] = {"model": f"{NS}:block/maglev_track/{along}"}
    json.dump({"variants": variants}, open(os.path.join(ROOT, 'blockstates', 'maglev_track.json'), 'w'), indent=2)

    texture().save(os.path.join(ROOT, 'textures', 'block', 'maglev_track.png'))
    # Krasnikov track: the same guideway, its magnets violet and teal, a violet glow down the floor (the tube's).
    texture((150, 70, 200), (40, 170, 160)).save(os.path.join(ROOT, 'textures', 'block', 'krasnikov_track.png'))
    krasnikov = os.path.join(ROOT, 'models', 'block', 'krasnikov_track')
    os.makedirs(krasnikov, exist_ok=True)
    for f in os.listdir(krasnikov): os.remove(os.path.join(krasnikov, f))
    json.dump({"parent": f"{NS}:block/maglev_track/obj_track", "render_type": "minecraft:cutout_mipped",
               "textures": {"0": f"{NS}:block/krasnikov_track", "particle": f"{NS}:block/krasnikov_track"}},
              open(os.path.join(krasnikov, 'obj_track.json'), 'w'), indent=2)
    for f in os.listdir(MODELS):
        if not f.endswith('.obj'): continue
        name = f[:-4]
        json.dump({"parent": f"{NS}:block/krasnikov_track/obj_track", "loader": "neoforge:obj", "flip_v": True,
                   "model": f"{NS}:models/block/maglev_track/{name}.obj"}, open(os.path.join(krasnikov, name + '.json'), 'w'), indent=2)
    with open(os.path.join(ROOT, 'blockstates', 'maglev_track.json')) as f:
        state = f.read().replace(f'{NS}:block/maglev_track/', f'{NS}:block/krasnikov_track/')
    with open(os.path.join(ROOT, 'blockstates', 'krasnikov_track.json'), 'w') as f:
        f.write(state)
    item_texture().save(os.path.join(ROOT, 'textures', 'item', 'maglev_track.png'))
    item_texture((150, 70, 200, 255), (40, 170, 160, 255)).save(os.path.join(ROOT, 'textures', 'item', 'krasnikov_track.png'))
    for old in ('maglev_track_mip.png', 'maglev_track_crossing.png'):
        p = os.path.join(ROOT, 'textures', 'block', old)
        if os.path.exists(p): os.remove(p)


if __name__ == '__main__':
    main()
